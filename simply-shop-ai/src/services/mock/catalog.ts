type Seed = Omit<Product, "currency" | "variants" | "inventory"> & {
  variants?: Product["variants"];
  inventory?: Product["inventory"];
};

function buildProduct(seed: Seed): Product {
  const inventory = seed.inventory ?? {
    status: "in_stock" as const,
    quantity: 24,
    deliveryEstimate: "Delivery in 2–4 days",
  };
  return {
    ...seed,
    currency: "INR",
    inventory,
    variants: seed.variants ?? [
      {
        id: `${seed.id}_default`,
        title: "Standard",
        optionName: "Configuration",
        price: seed.price,
        inventory,
        sku: `${seed.handle}-std`,
      },
    ],
  };
}

